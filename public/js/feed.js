async function feedShare(idea) {
  const url = `${location.origin}${location.pathname}#idea=${encodeURIComponent(idea.id)}`;
  if (navigator.share) {
    try {
      await navigator.share({ title: idea.title || "BQ Connect", url });
    } catch {}
    return;
  }
  try {
    await navigator.clipboard.writeText(url);
    feedToast(t("fpCopied"));
  } catch {}
}

function feedVideos() {
  if (feedWatcher) return feedWatcher;
  feedWatcher = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      const video = entry.target;
      if (!video.isConnected) {
        feedWatcher.unobserve(video);
        return;
      }
      if (entry.intersectionRatio >= 0.6) {
        document.querySelectorAll("video.fp-video").forEach((other) => {
          if (other !== video) other.pause();
        });
        video.muted = feedMuted;
        video.play().catch(() => {});
      } else {
        video.pause();
      }
    });
  }, { threshold: [0, 0.6] });
  return feedWatcher;
}

