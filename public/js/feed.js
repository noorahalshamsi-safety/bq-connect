const VIEW_ICON = "M4 20v-7M9.5 20V9M15 20V4M20.5 20v-10";
const viewSent = new Set();
const viewQueue = new Set();
const viewTimers = new WeakMap();
let viewFlush = 0;
let viewWatcher = null;

function compactCount(n) {
  const value = Number(n) || 0;
  return value ? new Intl.NumberFormat("en-US", { notation: "compact", maximumFractionDigits: 1 }).format(value) : "";
}

function queueView(idea) {
  if (!idea || idea.mine || viewSent.has(idea.id) || !selectedPerson || !selectedPerson.token) return;
  viewSent.add(idea.id);
  viewQueue.add(idea.id);
  clearTimeout(viewFlush);
  viewFlush = setTimeout(flushViews, 1500);
}

async function flushViews() {
  clearTimeout(viewFlush);
  if (!viewQueue.size || !selectedPerson || !selectedPerson.token) return;
  const ids = [...viewQueue];
  viewQueue.clear();
  try {
    const response = await fetch("/api/views", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ token: selectedPerson.token, ids }),
      keepalive: true,
    });
    if (!response.ok) return;
    const data = await response.json();
    Object.entries(data.views || {}).forEach(([id, count]) => paintViews(id, count));
  } catch {
    // A lost view count is harmless.
  }
}

function paintViews(id, count) {
  const idea = ideas.find((item) => item.id === id);
  if (idea) idea.views = count;
  document.querySelectorAll("[data-views]").forEach((node) => {
    if (node.dataset.views !== id) return;
    node.textContent = compactCount(count) || (node.closest(".twd-views") ? "0" : "");
  });
}

function watchViews(card, idea) {
  if (!("IntersectionObserver" in window) || idea.mine || viewSent.has(idea.id)) return;
  if (!viewWatcher) {
    viewWatcher = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        const node = entry.target;
        clearTimeout(viewTimers.get(node));
        if (!node.isConnected || viewSent.has(node.dataset.id)) {
          viewWatcher.unobserve(node);
          return;
        }
        if (!entry.isIntersecting) return;
        viewTimers.set(node, setTimeout(() => {
          if (!node.isConnected) return;
          viewWatcher.unobserve(node);
          queueView(ideas.find((item) => item.id === node.dataset.id));
        }, 1000));
      });
    }, { threshold: 0.5 });
  }
  viewWatcher.observe(card);
}

document.addEventListener("visibilitychange", () => {
  if (document.visibilityState === "hidden") flushViews();
});

