function ideaSlides(idea) {
  const slides = [];
  const cover = slideBase("cover");
  const top = document.createElement("div");
  top.className = "fp-slide-top";
  const kicker = document.createElement("span");
  kicker.className = "fp-kicker";
  kicker.textContent = idea.number ? `${t("typeIdea")} ${pad(idea.number)}` : t("typeIdea");
  const pill = document.createElement("span");
  pill.className = `fp-status ${idea.status || "received"}`;
  pill.textContent = statusLabel(idea.status || "received");
  top.append(kicker, pill);
  cover.append(top, slideText(idea.title || excerpt(idea.text, 90), "fp-cover-title"));
  if (idea.title && idea.text) cover.appendChild(slideText(excerpt(idea.text, 140), "fp-cover-lead"));
  if (idea.place && displayPlace(idea.place)) cover.appendChild(slideText(displayPlace(idea.place), "fp-cover-place"));
  slides.push(cover);

  feedGallery(idea).forEach((media) => slides.push({ media }));

  if (idea.problem) {
    const slide = slideBase("problem");
    slide.append(slideLabel(t("labelProblem")), slideText(idea.problem, "fp-slide-body"));
    slides.push(slide);
  }

  const pros = Array.isArray(idea.pros) ? idea.pros : [];
  const cons = Array.isArray(idea.cons) ? idea.cons : [];
  if (pros.length || cons.length) {
    const slide = slideBase("weigh");
    [[pros, "labelPros", "pros"], [cons, "labelCons", "cons"]].forEach(([items, key, kind]) => {
      if (!items.length) return;
      const box = document.createElement("div");
      box.className = `fp-weigh ${kind}`;
      box.appendChild(slideLabel(t(key)));
      const list = document.createElement("ul");
      items.slice(0, 4).forEach((item) => {
        const li = document.createElement("li");
        li.textContent = item;
        list.appendChild(li);
      });
      box.appendChild(list);
      slide.appendChild(box);
    });
    slides.push(slide);
  }

  if (idea.impact) {
    const slide = slideBase("impact");
    slide.append(slideLabel(t("labelImpact")), slideText(idea.impact, "fp-slide-body"));
    slides.push(slide);
  }
  return slides;
}

