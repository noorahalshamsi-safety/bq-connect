function tweetText(idea) {
  const lead = idea.title && !String(idea.text || "").startsWith(idea.title) ? idea.title : "";
  const full = idea.type === "article" ? excerpt(idea.text, 280) : String(idea.text || "").trim();
  if (!lead && !full) return null;
  const box = document.createElement("div");
  box.className = "tw-text";
  if (lead) {
    const title = document.createElement("strong");
    title.className = "tw-title";
    title.textContent = lead;
    box.appendChild(title);
  }
  if (full) {
    const long = full.length > 280 || full.split("\n").length > 6;
    const p = document.createElement("p");
    fillRichText(p, long ? excerpt(full.split("\n").slice(0, 6).join("\n"), 260) : full);
    box.appendChild(p);
    if (long) {
      const more = document.createElement("button");
      more.type = "button";
      more.className = "fp-more-text";
      more.textContent = t("fpMore");
      more.addEventListener("click", (event) => {
        event.stopPropagation();
        fillRichText(p, full);
        more.remove();
      });
      box.appendChild(more);
    }
  }
  const translate = translateControl([lead, idea.type === "article" ? idea.text : full].filter(Boolean).join("\n"));
  if (translate) box.appendChild(translate);
  return box;
}

