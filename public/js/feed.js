function exSearchResults(body, query) {
  const tag = query.startsWith("#") ? normalizeTag(query) : "";
  const ready = Boolean(tag) || exHits.query === query;
  const words = searchWords(query);
  const posts = ideas
    .filter((idea) => idea.type !== "story")
    .filter((idea) => (tag ? ideaTags(idea).includes(tag) : ideaMatches(idea, words)));
  const byDate = (a, b) => new Date(b.createdAt) - new Date(a.createdAt);

  if (exQTab === "people") {
    const people = tag ? null : exPeopleSection(Infinity);
    if (people) body.appendChild(people);
    if (!tag && exHits.departments.length) {
      const section = document.createElement("section");
      section.className = "ex-section";
      section.appendChild(exHeading(t("searchDepts")));
      exHits.departments.forEach((department) => section.appendChild(exDeptRow({ department, members: (exDepts || []).find((group) => group.department === department)?.members || 0 })));
      body.appendChild(section);
    }
  } else if (exQTab === "media") {
    const media = posts.filter((idea) => idea.media).sort(byDate).slice(0, 60);
    if (media.length) {
      const grid = document.createElement("div");
      grid.className = "ig-grid ex-media";
      media.forEach((idea) => grid.appendChild(profileTile(idea)));
      body.appendChild(grid);
    }
  } else {
    if (exQTab === "top" && !tag) {
      const people = exPeopleSection(3);
      if (people) body.appendChild(people);
    }
    const list = exQTab === "latest"
      ? posts.slice().sort(byDate)
      : posts.slice().sort((a, b) => exScore(b) - exScore(a) || byDate(a, b));
    if (list.length) body.appendChild(exTweets(list.slice(0, 40)));
  }
  if (!body.childElementCount && (ready || exQTab === "media" || exQTab === "latest")) {
    body.appendChild(exEmpty(tf("exNoResults", { q: query })));
  }
}

