function onTaps(node, single, double) {
  let timer = 0;
  let last = 0;
  node.addEventListener("click", (event) => {
    if (event.target.closest("button, a, input")) return;
    const now = Date.now();
    if (now - last < 300) {
      clearTimeout(timer);
      last = 0;
      double(event);
      return;
    }
    last = now;
    timer = setTimeout(() => single(event), 300);
  });
}

