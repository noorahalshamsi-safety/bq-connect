function carousel(idea, slides, card, dots) {
  const stage = document.createElement("div");
  stage.className = "fp-stage fp-carousel-wrap";
  const track = document.createElement("div");
  track.className = "fp-carousel";
  slides.forEach((slide) => {
    if (slide.media) {
      const box = slideBase("media");
      box.appendChild(isVideoSrc(slide.media) ? feedVideo(idea, slide.media, box) : feedImage(idea, slide.media));
      track.appendChild(box);
    } else {
      track.appendChild(slide);
    }
  });
  stage.appendChild(track);
  if (slides.length < 2) return stage;

  const counter = document.createElement("span");
  counter.className = "fp-counter";
  stage.append(counter, dots);
  for (let i = 0; i < slides.length; i += 1) dots.appendChild(document.createElement("i"));
  const paint = (index) => {
    counter.textContent = `${index + 1}/${slides.length}`;
    [...dots.children].forEach((dot, i) => dot.classList.toggle("on", i === index));
  };
  const indexNow = () => Math.round(Math.abs(track.scrollLeft) / Math.max(1, track.clientWidth));
  track.addEventListener("scroll", () => {
    const index = indexNow();
    feedSlideAt.set(idea.id, index);
    paint(index);
  }, { passive: true });
  const start = Math.min(feedSlideAt.get(idea.id) || 0, slides.length - 1);
  paint(start);
  if (start) {
    requestAnimationFrame(() => {
      const rtl = getComputedStyle(track).direction === "rtl";
      track.scrollLeft = (rtl ? -1 : 1) * start * track.clientWidth;
    });
  } else {
    const hint = document.createElement("span");
    hint.className = "fp-swipe";
    hint.textContent = t("fpSwipe");
    stage.appendChild(hint);
    track.addEventListener("scroll", () => hint.remove(), { once: true, passive: true });
  }
  return stage;
}

