const TFA_ERRORS = { wrong_password: "pwWrong", bad_code: "totpWrong", limited: "loginLocked" };

function tfaNode(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function tfaButton(label, kind) {
  const button = tfaNode("button", kind === "ghost" ? "btn btn-ghost" : "btn", label);
  button.type = "button";
  return button;
}

function tfaInput(kind) {
  const input = tfaNode("input", kind === "code" ? "tfa-code-input" : "");
  input.dir = "ltr";
  if (kind === "password") {
    input.type = "password";
    input.autocomplete = "current-password";
    input.maxLength = 128;
    input.placeholder = t("pwCurrent");
  } else {
    input.inputMode = kind === "code" ? "numeric" : "text";
    input.autocomplete = kind === "code" ? "one-time-code" : "off";
    input.maxLength = kind === "code" ? 6 : 11;
    input.placeholder = kind === "code" ? "••••••" : t("totpCodeOrRecovery");
  }
  return input;
}

async function tfaCall(body, error) {
  error.textContent = "";
  try {
    const { status, ok, data } = await postJson("/api/2fa", { token: selectedPerson.token, ...body });
    if (status === 401) {
      clearSession();
      return null;
    }
    if (!ok) {
      error.textContent = t(TFA_ERRORS[data.error] || "loginFailed");
      return null;
    }
    return data;
  } catch {
    error.textContent = t("loginFailed");
    return null;
  }
}

