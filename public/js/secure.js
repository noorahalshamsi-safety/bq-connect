const EMAIL_CHANGE_ERRORS = { ...LINK_ERRORS, wrong_password: "pwWrong", same_email: "emailSame" };

async function submitEmailChange() {
  const error = document.querySelector("#em-error");
  const done = document.querySelector("#em-done");
  const button = document.querySelector("#em-btn");
  const email = document.querySelector("#em-new").value.trim();
  const password = document.querySelector("#em-password").value;
  const code = digitsOnly(document.querySelector("#em-code").value);
  error.textContent = "";
  if (!emailCodeStep && (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) || !password)) {
    error.textContent = t(password ? "badEmail" : "emailNeedPassword");
    return;
  }
  if (emailCodeStep && code.length !== 6) {
    error.textContent = t("totpShort");
    return;
  }
  if (button.disabled) return;
  button.disabled = true;
  try {
    const body = emailCodeStep ? { op: "confirm", code } : { op: "send", email, password };
    const { status, ok, data } = await postJson("/api/email", { token: selectedPerson.token, ...body });
    if (status === 401) {
      clearSession();
      return;
    }
    if (!ok) {
      if (data.error === "code_expired") setEmailChangeStep(false);
      document.querySelector("#em-code").value = "";
      error.textContent = t(EMAIL_CHANGE_ERRORS[data.error] || "loginFailed");
      return;
    }
    if (data.sent) {
      setEmailChangeStep(true);
      done.textContent = tf("linkSent", { email: `\u2068${data.email || ""}\u2069` });
      done.hidden = false;
      document.querySelector("#em-code").focus();
      return;
    }
    selectedPerson = { ...selectedPerson, ...data.person, token: selectedPerson.token };
    setEmailChangeStep(false);
    document.querySelector("#set-email").textContent = tf("emailLinked", { email: `\u2068${selectedPerson.email}\u2069` });
    done.textContent = t("emailChanged");
    done.hidden = false;
  } catch {
    error.textContent = t("loginFailed");
  } finally {
    button.disabled = false;
  }
}

