async function submitTotp() {
  const input = document.querySelector("#totp-code");
  const error = document.querySelector("#totp-error");
  const button = document.querySelector("#totp-btn");
  const code = totpRecovery ? input.value.trim() : digitsOnly(input.value);
  error.textContent = "";
  if (totpRecovery ? code.replace(/[^A-Za-z0-9]/g, "").length !== 10 : code.length !== 6) {
    error.textContent = t(totpRecovery ? "totpRecoveryShort" : "totpShort");
    return;
  }
  if (button.disabled) return;
  button.disabled = true;
  try {
    const { status, ok, data } = await postJson("/api/login-2fa", { ticket: totpTicket, code, app: standaloneApp() });
    if (ok && loginStep(data)) {
      totpTicket = "";
      input.value = "";
      return;
    }
    if (status === 401 && data.error === "expired") {
      loginExpired();
      return;
    }
    input.value = "";
    error.textContent = t(status === 429 ? "loginLocked" : status === 401 ? "totpWrong" : "loginFailed");
  } catch {
    error.textContent = t("loginFailed");
  } finally {
    button.disabled = false;
  }
}

