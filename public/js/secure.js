function loginStep(data) {
  if (data.needTotp && data.ticket) openTotpStep(data.ticket);
  else if (data.needSetup && data.ticket) openEnrollStep(data.ticket);
  else if (data.needEmail && data.ticket) openEmailStep(data.ticket, data.mailOn);
  else if (data.token) {
    badgeInput.value = "";
    saveSession(data.person, data.token);
    loadIdeas();
  } else return false;
  return true;
}

function loginExpired() {
  totpTicket = "";
  linkTicket = "";
  gateCard("login");
  loginError.textContent = t("totpExpired");
}

async function openEnrollStep(ticket) {
  const body = document.querySelector("#enroll-body");
  gateCard("enroll");
  const error = tfaNode("p", "form-error");
  body.replaceChildren(tfaNode("p", "device-empty", t("devicesLoading")));
  try {
    const { status, ok, data } = await postJson("/api/login-2fa", { op: "setup", ticket });
    if (status === 401) {
      loginExpired();
      return;
    }
    if (!ok) {
      error.textContent = t(status === 429 ? "loginLocked" : "loginFailed");
      body.replaceChildren(error);
      return;
    }
    tfaSetupView(body, data, async (code, codeError) => {
      try {
        const reply = await postJson("/api/login-2fa", { op: "enroll", ticket, code, app: standaloneApp() });
        if (reply.status === 401) {
          loginExpired();
          return true;
        }
        if (!reply.ok) {
          codeError.textContent = t(reply.status === 429 ? "loginLocked" : "totpWrong");
          return false;
        }
        const next = { ...reply.data };
        delete next.recovery;
        tfaRecoveryView(body, reply.data.recovery || [], true, () => loginStep(next), t("enrollContinue"));
        return true;
      } catch {
        codeError.textContent = t("loginFailed");
        return false;
      }
    });
  } catch {
    error.textContent = t("loginFailed");
    body.replaceChildren(error);
  }
}

