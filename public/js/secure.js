async function submitLink() {
  const error = document.querySelector("#link-error");
  const done = document.querySelector("#link-done");
  const button = document.querySelector("#link-btn");
  const email = document.querySelector("#link-email").value.trim();
  const code = digitsOnly(document.querySelector("#link-code").value);
  error.textContent = "";
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
    error.textContent = t("badEmail");
    return;
  }
  if (linkCodeStep && code.length !== 6) {
    error.textContent = t("totpShort");
    return;
  }
  if (button.disabled) return;
  button.disabled = true;
  try {
    const body = linkCodeStep ? { op: "email-confirm", ticket: linkTicket, code } : { op: "email", ticket: linkTicket, email };
    const { status, ok, data } = await postJson("/api/login-2fa", { ...body, app: standaloneApp() });
    if (status === 401) {
      loginExpired();
      return;
    }
    if (!ok) {
      if (data.error === "code_expired") setLinkStep(false);
      document.querySelector("#link-code").value = "";
      error.textContent = t(LINK_ERRORS[data.error] || "loginFailed");
      return;
    }
    if (data.sent) {
      setLinkStep(true);
      done.textContent = tf("linkSent", { email: `\u2068${data.email || ""}\u2069` });
      done.hidden = false;
      document.querySelector("#link-code").focus();
      return;
    }
    linkTicket = "";
    loginStep(data);
  } catch {
    error.textContent = t("loginFailed");
  } finally {
    button.disabled = false;
  }
}

