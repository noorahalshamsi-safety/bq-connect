function gateCard(name) {
  const splash = document.querySelector("#splash");
  if (splash) splash.hidden = true;
  document.querySelectorAll("#gate .gate-card").forEach((card) => {
    card.hidden = card.id !== `${name}-form`;
  });
  const card = document.querySelector(`#${name}-form`);
  const first = card && card.querySelector("input");
  if (first) first.focus();
}

function digitsOnly(value) {
  return asciiDigits(value).replace(/\D/g, "");
}

function cleanBadgeInput(value) {
  return digitsOnly(value).replace(/^0+/, "");
}

async function postJson(url, body) {
  const response = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  const data = await response.json().catch(() => ({}));
  return { status: response.status, ok: response.ok, data };
}

async function loginPerson() {
  const badge = cleanBadgeInput(badgeInput.value);
  const passwordInput = document.querySelector("#password");
  const password = passwordInput.value;
  loginError.textContent = "";
  if (!badge || !password) {
    loginError.textContent = t("loginMissing");
    return;
  }
  verifyButton.disabled = true;
  verifyButton.textContent = t("verifying");
  try {
    const { status, ok, data } = await postJson("/api/login", { badge, password, app: standaloneApp() });
    if (status === 429) {
      loginError.textContent = t("loginLocked");
      return;
    }
    if (status === 403 && data && data.error === "banned") {
      loginError.textContent = t("loginBanned");
      return;
    }
    if (!ok || !loginStep(data)) {
      loginError.textContent = t(status === 401 ? "loginWrong" : "loginFailed");
      return;
    }
    passwordInput.value = "";
  } catch {
    loginError.textContent = t("loginFailed");
  } finally {
    verifyButton.disabled = false;
    verifyButton.textContent = t("loginButton");
  }
}

